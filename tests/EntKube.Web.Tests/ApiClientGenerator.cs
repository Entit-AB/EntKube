using System.Text;
using System.Text.Json;

namespace EntKube.Web.Tests;

/// <summary>
/// Emits <c>EntKube.ApiClient</c> from the committed OpenAPI document
/// (<c>docs/decomposition.md</c> item 8).
///
/// <para><b>Why a generator in this repository rather than NSwag or Kiota.</b> Two things in this
/// document defeat a stock generator, and both were measured rather than guessed:</para>
/// <list type="bullet">
///   <item><description>.NET 10 emits a number as <c>type: ["integer","string"]</c> with a
///   <c>pattern</c> constraining the string form — 109 properties here. A strict reader treats
///   that union as "integer or string" and emits <c>object</c>, which is the
///   <c>UndescribedSuccessBodies</c> problem arriving again through the tool meant to solve
///   it;</description></item>
///   <item><description>six success bodies are <c>application/scim+json</c>, which generators
///   that key on <c>application/json</c> skip entirely — and skipping them silently would waste
///   the whole SCIM typing exercise.</description></item>
/// </list>
///
/// <para>⚠️ <b>Money is <c>decimal</c>, not <c>double</c>, and that is a deliberate departure
/// from a literal reading of the document.</b> The server declares <c>decimal</c> — see
/// <c>ClusterRateResponse.CpuCoreHourCost</c> — but .NET's OpenAPI generation writes
/// <c>format: double</c>, losing the distinction. A client that read a cost into a
/// <c>double</c> would put binary floating-point error into a billing API, and this repository
/// has already shipped eight cost-arithmetic defects. <c>number</c> therefore becomes
/// <c>decimal</c>, which round-trips every value the server can send.</para>
///
/// <para>⚠️ The DTOs are <b>init-only properties, not positional records</b>. A positional record
/// makes the document's field ORDER part of the client's source compatibility, so reordering two
/// members of a response — which changes nothing on the wire — would break every caller. The
/// wire name is carried by <c>[JsonPropertyName]</c> read straight out of the document, which is
/// also what keeps SCIM's capital-R <c>Resources</c> correct without a special case.</para>
/// </summary>
internal static class ApiClientGenerator
{
    internal const string RelativePath = "src/EntKube.ApiClient/Generated/EntKubeApi.g.cs";

    private static readonly HashSet<string> Keywords = new(StringComparer.Ordinal)
    {
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked",
        "class", "const", "continue", "decimal", "default", "delegate", "do", "double", "else",
        "enum", "event", "explicit", "extern", "false", "finally", "fixed", "float", "for",
        "foreach", "goto", "if", "implicit", "in", "int", "interface", "internal", "is", "lock",
        "long", "namespace", "new", "null", "object", "operator", "out", "override", "params",
        "private", "protected", "public", "readonly", "ref", "return", "sbyte", "sealed", "short",
        "sizeof", "stackalloc", "static", "string", "struct", "switch", "this", "throw", "true",
        "try", "typeof", "uint", "ulong", "unchecked", "unsafe", "ushort", "using", "virtual",
        "void", "volatile", "while",
    };

    internal static string Generate(string documentJson)
    {
        using JsonDocument document = JsonDocument.Parse(documentJson);
        JsonElement root = document.RootElement;

        StringBuilder output = new();
        Header(output);
        Schemas(output, root);
        Operations(output, root);

        // ⚠️ No closing brace here: the namespace is file-scoped, and Operations already closes
        // the class it opened.
        return output.ToString();
    }

    private static void Header(StringBuilder output) => output.Append(
        """
        // <auto-generated>
        //     Generated from docs/openapi/v1.json by ApiClientGenerator.
        //
        //     DO NOT EDIT. Regenerate with:
        //         ENTKUBE_UPDATE_API_CLIENT=1 dotnet test --filter ApiClientGeneratedTests
        //
        //     The document itself is regenerated with ENTKUBE_UPDATE_OPENAPI=1, so the chain is
        //     application -> document -> client, each step ratcheted by its own test.
        // </auto-generated>
        #nullable enable

        using System.Text.Json;
        using System.Text.Json.Serialization;

        namespace EntKube.ApiClient;


        """);

    // ── schemas ───────────────────────────────────────────────────────────────

    private static void Schemas(StringBuilder output, JsonElement root)
    {
        if (!root.TryGetProperty("components", out JsonElement components)
            || !components.TryGetProperty("schemas", out JsonElement schemas))
        {
            return;
        }

        foreach (JsonProperty schema in schemas.EnumerateObject().OrderBy(s => s.Name, StringComparer.Ordinal))
        {
            output.Append($"/// <summary>The <c>{schema.Name}</c> schema, as the document defines it.</summary>\n");
            output.Append($"public sealed record {schema.Name}\n{{\n");

            if (schema.Value.TryGetProperty("properties", out JsonElement properties))
            {
                bool first = true;
                foreach (JsonProperty property in properties.EnumerateObject())
                {
                    if (!first) output.Append('\n');
                    first = false;

                    output.Append($"    [JsonPropertyName(\"{property.Name}\")]\n");
                    output.Append(
                        $"    public {TypeOf(property.Value)} {Pascal(property.Name)} {{ get; init; }}\n");
                }
            }

            output.Append("}\n\n");
        }
    }

    /// <summary>
    /// The C# type for a schema node. ⚠️ The nullability decision comes from <c>"null"</c>
    /// appearing in the type ARRAY, not from the <c>required</c> list: a member can be required
    /// and still nullable, which is most of this document.
    /// </summary>
    private static string TypeOf(JsonElement node)
    {
        if (node.TryGetProperty("$ref", out JsonElement reference))
        {
            return $"{Reference(reference.GetString())}?";
        }

        List<string> types = [];
        if (node.TryGetProperty("type", out JsonElement type))
        {
            if (type.ValueKind == JsonValueKind.Array)
            {
                types.AddRange(type.EnumerateArray().Select(t => t.GetString() ?? ""));
            }
            else
            {
                types.Add(type.GetString() ?? "");
            }
        }

        bool nullable = types.Remove("null");
        string format = node.TryGetProperty("format", out JsonElement f) ? f.GetString() ?? "" : "";

        if (types.Contains("array"))
        {
            string item = node.TryGetProperty("items", out JsonElement items) ? TypeOf(items) : "object?";
            return $"IReadOnlyList<{item}>?";
        }

        // ⚠️ `integer`/`number` beside `string` is one type, not a union: .NET writes a number
        // that way to allow a string-encoded form on input. Taking the union literally is what
        // makes a stock generator emit `object` for every count and every price in this document.
        string scalar =
            types.Contains("integer") ? (format == "int64" ? "long" : "int")
            : types.Contains("number") ? "decimal"
            : types.Contains("boolean") ? "bool"
            : types.Contains("string") ? format switch
            {
                "uuid" => "Guid",
                "date-time" => "DateTime",
                _ => "string",
            }
            : "object";

        // A reference type is already nullable-annotated; a value type needs the `?`.
        return scalar is "string" or "object"
            ? scalar + "?"
            : nullable ? scalar + "?" : scalar;
    }

    private static string Reference(string? pointer) =>
        pointer?.Split('/').LastOrDefault() ?? "object";

    // ── operations ────────────────────────────────────────────────────────────

    private static void Operations(StringBuilder output, JsonElement root)
    {
        output.Append(
            """
            /// <summary>
            /// Every operation the API describes, one method each, generated from the document.
            ///
            /// <para>Wraps <see cref="EntKubeApiClient"/> rather than <c>HttpClient</c>, so the
            /// status-to-advice mapping, the 207 partial-success rule and the token and timeout
            /// handling stay in one hand-written place and are not regenerated.</para>
            /// </summary>
            public sealed class EntKubeApi(EntKubeApiClient transport)
            {

            """);

        List<(string Id, string Method, string Path, JsonElement Operation)> operations = [];

        foreach (JsonProperty path in root.GetProperty("paths").EnumerateObject())
        {
            foreach (JsonProperty verb in path.Value.EnumerateObject())
            {
                if (verb.Name is not ("get" or "post" or "put" or "patch" or "delete")) continue;

                string id = verb.Value.TryGetProperty("operationId", out JsonElement operationId)
                    ? operationId.GetString() ?? ""
                    : "";

                operations.Add((id, verb.Name.ToUpperInvariant(), path.Name, verb.Value));
            }
        }

        bool first = true;
        foreach ((string id, string method, string path, JsonElement operation) in
            operations.OrderBy(o => o.Id, StringComparer.Ordinal))
        {
            if (!first) output.Append('\n');
            first = false;
            Operation(output, id, method, path, operation);
        }

        output.Append("}\n");
    }

    private static void Operation(
        StringBuilder output, string id, string method, string path, JsonElement operation)
    {
        List<(string Name, string Type, bool Required, string In)> parameters = [];

        if (operation.TryGetProperty("parameters", out JsonElement declared))
        {
            foreach (JsonElement parameter in declared.EnumerateArray())
            {
                string name = parameter.GetProperty("name").GetString() ?? "";
                string where = parameter.TryGetProperty("in", out JsonElement i) ? i.GetString() ?? "" : "";
                bool required = parameter.TryGetProperty("required", out JsonElement r) && r.GetBoolean();
                string type = parameter.TryGetProperty("schema", out JsonElement schema)
                    ? TypeOf(schema)
                    : "string?";

                parameters.Add((name, type, required, where));
            }
        }

        // Path parameters in the order the path mentions them, so the signature reads like the
        // route; then the query, required before optional, alphabetical for determinism.
        List<(string Name, string Type, bool Required, string In)> ordered =
        [
            .. parameters.Where(p => p.In == "path").OrderBy(p => path.IndexOf('{' + p.Name + '}', StringComparison.Ordinal)),
            .. parameters.Where(p => p.In == "query" && p.Required).OrderBy(p => p.Name, StringComparer.Ordinal),
            .. parameters.Where(p => p.In == "query" && !p.Required).OrderBy(p => p.Name, StringComparer.Ordinal),
        ];

        string? bodyType = null;
        if (operation.TryGetProperty("requestBody", out JsonElement body)
            && body.TryGetProperty("content", out JsonElement bodyContent))
        {
            foreach (JsonProperty media in bodyContent.EnumerateObject())
            {
                if (media.Value.TryGetProperty("schema", out JsonElement schema))
                {
                    bodyType = TypeOf(schema).TrimEnd('?');
                    break;
                }
            }
        }

        string returnType = ReturnType(operation);

        List<string> signature = [];
        foreach ((string name, string type, bool required, string where) in ordered.Where(p => p.In == "path"))
        {
            signature.Add($"{type.TrimEnd('?')} {Identifier(name)}");
        }

        if (bodyType is not null)
        {
            signature.Add($"{bodyType} body");
        }

        foreach ((string name, string type, bool required, _) in ordered.Where(p => p.In == "query"))
        {
            signature.Add(required
                ? $"{type.TrimEnd('?')} {Identifier(name)}"
                : $"{(type.EndsWith('?') ? type : type + "?")} {Identifier(name)} = null");
        }

        signature.Add("CancellationToken ct = default");

        output.Append($"    /// <summary><c>{method} {path}</c></summary>\n");
        output.Append($"    public async Task<{returnType}> {id}Async(\n");
        output.Append("        " + string.Join(", ", signature) + ")\n    {\n");

        string route = path;
        foreach ((string name, string type, _, string where) in ordered.Where(p => p.In == "path"))
        {
            string value = type.TrimEnd('?') is "string" ? Identifier(name) : $"{Identifier(name)}.ToString()";
            route = route.Replace('{' + name + '}', $"{{Uri.EscapeDataString({value})}}", StringComparison.Ordinal);
        }

        List<(string Name, string Type, bool Required, string In)> query = [.. ordered.Where(p => p.In == "query")];

        if (query.Count == 0)
        {
            output.Append($"        string path = $\"{route}\";\n");
        }
        else
        {
            output.Append($"        string path = $\"{route}\" + EntKubeApiClient.QueryString(\n");
            // ⚠️ The null-conditional belongs only on an OPTIONAL parameter. A required query
            // parameter is a non-nullable value type in the signature, and `?.` on one does not
            // compile — which is how `clusterId` on the log query broke the build.
            output.Append("            " + string.Join(",\n            ", query.Select(p =>
                $"(\"{p.Name}\", {Identifier(p.Name)}{(
                    p.Type.TrimEnd('?') is "string" ? ""
                    : p.Required ? ".ToString()"
                    : "?.ToString()")})")));
            output.Append(");\n");
        }

        string call = method switch
        {
            "GET" => "transport.GetAsync(path, ct)",
            "DELETE" => "transport.DeleteAsync(path, ct)",
            _ when bodyType is not null => $"transport.SendJsonAsync(HttpMethod.{Pascal(method.ToLowerInvariant())}, path, body, ct)",
            _ => "transport.PostAsync(path, ct)",
        };

        output.Append($"\n        ApiResult result = await {call};\n");
        output.Append($"        return {returnType}.From(result);\n");
        output.Append("    }\n");
    }

    /// <summary>
    /// The success body's type. ⚠️ The 2xx is chosen by the LOWEST success status the operation
    /// declares, which is the one a caller gets on the ordinary path — and an operation declaring
    /// only a 204 has no body, so it returns the non-generic response.
    /// </summary>
    private static string ReturnType(JsonElement operation)
    {
        if (!operation.TryGetProperty("responses", out JsonElement responses))
        {
            return "ApiResponse";
        }

        foreach (JsonProperty response in responses.EnumerateObject()
            .Where(r => r.Name.StartsWith('2'))
            .OrderBy(r => r.Name, StringComparer.Ordinal))
        {
            if (!response.Value.TryGetProperty("content", out JsonElement content))
            {
                continue;
            }

            foreach (JsonProperty media in content.EnumerateObject())
            {
                if (!media.Value.TryGetProperty("schema", out JsonElement schema)) continue;

                string type = TypeOf(schema).TrimEnd('?');
                return type is "object" ? "ApiResponse" : $"ApiResponse<{type}>";
            }
        }

        return "ApiResponse";
    }

    // ── names ─────────────────────────────────────────────────────────────────

    private static string Pascal(string name) =>
        name.Length == 0 ? name : char.ToUpperInvariant(name[0]) + name[1..];

    private static string Camel(string name) =>
        name.Length == 0 ? name : char.ToLowerInvariant(name[0]) + name[1..];

    private static string Identifier(string name)
    {
        string camel = Camel(name);
        return Keywords.Contains(camel) ? "@" + camel : camel;
    }
}
